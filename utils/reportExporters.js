const ExcelJS = require('exceljs');
const PDFDocument = require('pdfkit');

const SYSTEM_NAME = 'Student Attendance Management System';
const PASS_MARK = 75; // percentages below this are shown in red

const stamp = (date) => `${date.toISOString().slice(0, 16).replace('T', ' ')} UTC`;

const filterText = (filters = {}) => {
  const parts = [];
  if (filters.className) parts.push(`Class: ${filters.className}`);
  if (filters.course) parts.push(`Course: ${filters.course}`);
  if (filters.studentStatus) parts.push(`Students: ${filters.studentStatus}`);
  return parts.length ? parts.join('  |  ') : 'None';
};

/* ==========================================================================
   EXCEL (ExcelJS)
   ========================================================================== */
const XL = {
  primary: 'FF1E3A8A',
  light: 'FFDBEAFE',
  zebra: 'FFF8FAFC',
  border: 'FFE2E8F0',
  text: 'FF1E293B',
  white: 'FFFFFFFF',
  success: 'FF16A34A',
  danger: 'FFDC2626',
};
const XL_STATUS = {
  Present: { fill: 'FFDCFCE7', font: 'FF166534' },
  Absent: { fill: 'FFFEE2E2', font: 'FF991B1B' },
  Leave: { fill: 'FFFEF3C7', font: 'FF92400E' },
};

const solid = (argb) => ({ type: 'pattern', pattern: 'solid', fgColor: { argb } });
const edge = { style: 'thin', color: { argb: XL.border } };
const BORDER = { top: edge, left: edge, bottom: edge, right: edge };
const pctFont = (pct) => ({ bold: true, color: { argb: pct >= PASS_MARK ? XL.success : XL.danger } });

const titleBand = (ws, lastCol) => {
  ws.mergeCells(1, 1, 1, lastCol);
  const cell = ws.getCell(1, 1);
  cell.value = 'STUDENT ATTENDANCE REPORT';
  cell.font = { bold: true, size: 16, color: { argb: XL.white } };
  cell.fill = solid(XL.primary);
  cell.alignment = { horizontal: 'center', vertical: 'middle' };
  ws.getRow(1).height = 32;
};

const subTitle = (ws, row, lastCol, text) => {
  ws.mergeCells(row, 1, row, lastCol);
  const cell = ws.getCell(row, 1);
  cell.value = text;
  cell.font = { bold: true, size: 12, color: { argb: XL.primary } };
  cell.alignment = { horizontal: 'center', vertical: 'middle' };
  ws.getRow(row).height = 24;
};

// Label (columns A:B) and value (column C to the last column); returns the next free row
const metaRows = (ws, startRow, lastCol, pairs) => {
  let r = startRow;
  for (const [label, value] of pairs) {
    ws.mergeCells(r, 1, r, 2);
    ws.mergeCells(r, 3, r, lastCol);

    const l = ws.getCell(r, 1);
    l.value = label;
    l.font = { bold: true, color: { argb: XL.primary } };
    l.fill = solid(XL.light);
    l.alignment = { vertical: 'middle' };

    const v = ws.getCell(r, 3);
    v.value = String(value);
    v.font = { color: { argb: XL.text } };
    v.alignment = { horizontal: 'left', vertical: 'middle', wrapText: true };

    ws.getRow(r).height = 20;
    r += 1;
  }
  return r;
};

const styleHeader = (row, count) => {
  row.height = 24;
  for (let c = 1; c <= count; c += 1) {
    const cell = row.getCell(c);
    cell.font = { bold: true, color: { argb: XL.white } };
    cell.fill = solid(XL.primary);
    cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true };
    cell.border = BORDER;
  }
};

const LIST_HEADERS = [
  '#', 'Student ID', 'Registration No.', 'Student Name', 'Class', 'Course/Program',
  'Present Days', 'Absent Days', 'Leave Days', 'Total Days', 'Attendance %',
];
const LIST_CENTER = new Set([1, 2, 5, 7, 8, 9, 10, 11]);

// Daily, weekly, monthly and class reports
const addListSheet = (wb, result, meta) => {
  const { report } = result;
  const o = report.overall;

  const ws = wb.addWorksheet('Attendance Report', {
    views: [{ showGridLines: false }],
    pageSetup: { paperSize: 9, orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  [6, 12, 18, 28, 12, 28, 10, 10, 10, 12, 14].forEach((w, i) => {
    ws.getColumn(i + 1).width = w;
  });

  titleBand(ws, 11);
  subTitle(ws, 2, 11, report.title);

  let r = metaRows(ws, 3, 11, [
    ['Period', report.period.label],
    ['Filters', filterText(report.filters)],
    ['Generated by', meta.generatedBy],
    ['Generated on', stamp(meta.generatedAt)],
  ]);
  r += 1;

  const headerRowNo = r;
  const headerRow = ws.getRow(r);
  headerRow.values = LIST_HEADERS;
  styleHeader(headerRow, 11);
  r += 1;

  report.students.forEach((s, i) => {
    const row = ws.getRow(r);
    row.values = [
      i + 1, s.studentId, s.registrationNumber, s.fullName, s.className, s.course,
      s.present, s.absent, s.leave, s.totalDays, s.percentage,
    ];
    row.height = 20;
    for (let c = 1; c <= 11; c += 1) {
      const cell = row.getCell(c);
      cell.border = BORDER;
      cell.font = { color: { argb: XL.text } };
      cell.alignment = { horizontal: LIST_CENTER.has(c) ? 'center' : 'left', vertical: 'middle' };
      if (i % 2 === 1) cell.fill = solid(XL.zebra);
    }
    const pct = row.getCell(11);
    pct.numFmt = '0.0"%"';
    pct.font = pctFont(s.percentage);
    r += 1;
  });

  // Overall row
  const totals = ws.getRow(r);
  totals.values = [
    `Overall (${o.students} students)`, '', '', '', '', '',
    o.present, o.absent, o.leave, o.totalDays, o.percentage,
  ];
  ws.mergeCells(r, 1, r, 6);
  totals.height = 22;
  for (let c = 1; c <= 11; c += 1) {
    const cell = totals.getCell(c);
    cell.border = BORDER;
    cell.fill = solid(XL.light);
    cell.font = { bold: true, color: { argb: XL.primary } };
    cell.alignment = { horizontal: c === 1 ? 'right' : 'center', vertical: 'middle' };
  }
  totals.getCell(11).numFmt = '0.0"%"';

  ws.autoFilter = {
    from: { row: headerRowNo, column: 1 },
    to: { row: headerRowNo + report.students.length, column: 11 },
  };
  ws.pageSetup.printTitlesRow = `${headerRowNo}:${headerRowNo}`;
};

// Student report
const addStudentSheet = (wb, result, meta) => {
  const { report } = result;
  const st = report.student;
  const o = report.overall;

  const ws = wb.addWorksheet('Student Report', {
    views: [{ showGridLines: false }],
    pageSetup: { paperSize: 9, orientation: 'portrait', fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  [16, 22, 28, 14, 14].forEach((w, i) => {
    ws.getColumn(i + 1).width = w;
  });

  titleBand(ws, 5);
  subTitle(ws, 2, 5, report.title);

  let r = metaRows(ws, 3, 5, [
    ['Student Name', st.fullName],
    ['Student ID', st.studentId],
    ['Registration No.', st.registrationNumber],
    ['Class', st.className],
    ['Course/Program', st.course],
    ['Year of Study', st.yearOfStudy],
    ['Period', report.period.label],
    ['Generated by', meta.generatedBy],
    ['Generated on', stamp(meta.generatedAt)],
  ]);
  r += 1;

  // Summary
  const sumHeader = ws.getRow(r);
  sumHeader.values = ['Present Days', 'Absent Days', 'Leave Days', 'Total Days', 'Attendance %'];
  styleHeader(sumHeader, 5);
  r += 1;

  const sumRow = ws.getRow(r);
  sumRow.values = [o.present, o.absent, o.leave, o.totalDays, o.percentage];
  sumRow.height = 28;
  for (let c = 1; c <= 5; c += 1) {
    const cell = sumRow.getCell(c);
    cell.border = BORDER;
    cell.font = { bold: true, size: 14, color: { argb: XL.text } };
    cell.alignment = { horizontal: 'center', vertical: 'middle' };
  }
  sumRow.getCell(5).numFmt = '0.0"%"';
  sumRow.getCell(5).font = { ...pctFont(o.percentage), size: 14 };
  r += 2;

  // Day-by-day history
  subTitle(ws, r, 5, 'Attendance History');
  r += 1;

  const headerRowNo = r;
  const header = ws.getRow(r);
  header.values = ['Date', 'Class', 'Course/Program', 'Session', 'Status'];
  styleHeader(header, 5);
  r += 1;

  report.records.forEach((rec, i) => {
    const row = ws.getRow(r);
    row.values = [rec.date, rec.className, rec.course, rec.session, rec.status];
    row.height = 20;
    for (let c = 1; c <= 5; c += 1) {
      const cell = row.getCell(c);
      cell.border = BORDER;
      cell.font = { color: { argb: XL.text } };
      cell.alignment = { horizontal: c === 2 || c === 3 ? 'left' : 'center', vertical: 'middle' };
      if (i % 2 === 1) cell.fill = solid(XL.zebra);
    }
    const style = XL_STATUS[rec.status];
    if (style) {
      const status = row.getCell(5);
      status.fill = solid(style.fill);
      status.font = { bold: true, color: { argb: style.font } };
    }
    r += 1;
  });

  ws.pageSetup.printTitlesRow = `${headerRowNo}:${headerRowNo}`;
};

const buildExcel = async (result, meta) => {
  const wb = new ExcelJS.Workbook();
  wb.creator = SYSTEM_NAME;
  wb.created = meta.generatedAt;

  if (result.reportType === 'student') addStudentSheet(wb, result, meta);
  else addListSheet(wb, result, meta);

  return Buffer.from(await wb.xlsx.writeBuffer());
};

/* ==========================================================================
   PDF (PDFKit)
   ========================================================================== */
const PDF = {
  primary: '#1E3A8A',
  light: '#DBEAFE',
  zebra: '#F8FAFC',
  border: '#E2E8F0',
  text: '#1E293B',
  muted: '#64748B',
  success: '#16A34A',
  danger: '#DC2626',
  white: '#FFFFFF',
};
const PDF_STATUS = {
  Present: { bg: '#DCFCE7', fg: '#166534' },
  Absent: { bg: '#FEE2E2', fg: '#991B1B' },
  Leave: { bg: '#FEF3C7', fg: '#92400E' },
};
const MARGIN = 40;
const ROW_H = 20;

const pctColor = (pct) => (pct >= PASS_MARK ? PDF.success : PDF.danger);

// Shortens text with "..." so it never overflows its cell (uses the current font)
const fit = (doc, value, width) => {
  let s = String(value === undefined || value === null ? '' : value);
  if (doc.widthOfString(s) <= width) return s;
  while (s.length > 1 && doc.widthOfString(`${s}...`) > width) s = s.slice(0, -1);
  return `${s}...`;
};

const drawBand = (doc) => {
  const w = doc.page.width - MARGIN * 2;
  doc.rect(0, 0, doc.page.width, 70).fill(PDF.primary);
  doc.fillColor(PDF.white).font('Helvetica-Bold').fontSize(18);
  doc.text('STUDENT ATTENDANCE REPORT', MARGIN, 20, { width: w, align: 'center', lineBreak: false });
  doc.font('Helvetica').fontSize(10);
  doc.text(SYSTEM_NAME, MARGIN, 46, { width: w, align: 'center', lineBreak: false });
};

const drawTiles = (doc, x, y, totalW, tiles) => {
  const gap = 8;
  const h = 46;
  const w = (totalW - gap * (tiles.length - 1)) / tiles.length;
  tiles.forEach((t, i) => {
    const tx = x + i * (w + gap);
    doc.roundedRect(tx, y, w, h, 4).fill(t.bg);
    doc.fillColor(t.fg).font('Helvetica-Bold').fontSize(16);
    doc.text(String(t.value), tx, y + 7, { width: w, align: 'center', lineBreak: false });
    doc.font('Helvetica').fontSize(8.5);
    doc.text(t.label, tx, y + 30, { width: w, align: 'center', lineBreak: false });
  });
  return y + h;
};

const tableWidth = (columns) => columns.reduce((sum, c) => sum + c.w, 0);

const drawHeaderRow = (doc, x, y, columns) => {
  doc.rect(x, y, tableWidth(columns), ROW_H).fill(PDF.primary);
  doc.fillColor(PDF.white).font('Helvetica-Bold').fontSize(8.5);
  let cx = x;
  for (const c of columns) {
    const label = fit(doc, c.label, c.w - 8);
    doc.text(label, cx + 4, y + 6, { width: c.w - 8, align: c.align || 'left', lineBreak: false });
    cx += c.w;
  }
};

// Draws a table that continues onto new pages (repeating the header); returns the next y
const drawTable = (doc, x, startY, columns, rows) => {
  const width = tableWidth(columns);
  const limit = () => doc.page.height - 55;
  let y = startY;

  if (y + ROW_H * 2 > limit()) {
    doc.addPage();
    y = MARGIN;
  }
  drawHeaderRow(doc, x, y, columns);
  y += ROW_H;

  rows.forEach((row, i) => {
    if (y + ROW_H > limit()) {
      doc.addPage();
      y = MARGIN;
      drawHeaderRow(doc, x, y, columns);
      y += ROW_H;
    }
    if (i % 2 === 1) doc.rect(x, y, width, ROW_H).fill(PDF.zebra);
    doc.moveTo(x, y + ROW_H).lineTo(x + width, y + ROW_H).lineWidth(0.5).strokeColor(PDF.border).stroke();

    let cx = x;
    for (const c of columns) {
      doc.fillColor(c.color ? c.color(row) : PDF.text);
      doc.font(c.bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5);
      const text = fit(doc, c.get(row), c.w - 8);
      doc.text(text, cx + 4, y + 6, { width: c.w - 8, align: c.align || 'left', lineBreak: false });
      cx += c.w;
    }
    y += ROW_H;
  });
  return y;
};

const drawTotalsRow = (doc, x, y, columns, span, label, values) => {
  doc.rect(x, y, tableWidth(columns), ROW_H).fill(PDF.light);
  const spanW = columns.slice(0, span).reduce((sum, c) => sum + c.w, 0);
  doc.fillColor(PDF.primary).font('Helvetica-Bold').fontSize(8.5);
  doc.text(label, x + 4, y + 6, { width: spanW - 8, align: 'right', lineBreak: false });
  let cx = x + spanW;
  columns.slice(span).forEach((c, i) => {
    doc.text(String(values[i]), cx + 4, y + 6, { width: c.w - 8, align: c.align || 'left', lineBreak: false });
    cx += c.w;
  });
};

const LIST_COLUMNS = [
  { label: '#', w: 25, align: 'center', get: (r) => r.n },
  { label: 'Student ID', w: 62, get: (r) => r.studentId },
  { label: 'Reg. No.', w: 95, get: (r) => r.registrationNumber },
  { label: 'Student Name', w: 150, get: (r) => r.fullName },
  { label: 'Class', w: 60, get: (r) => r.className },
  { label: 'Course/Program', w: 140, get: (r) => r.course },
  { label: 'Present', w: 45, align: 'center', get: (r) => r.present },
  { label: 'Absent', w: 45, align: 'center', get: (r) => r.absent },
  { label: 'Leave', w: 40, align: 'center', get: (r) => r.leave },
  { label: 'Total', w: 40, align: 'center', get: (r) => r.totalDays },
  {
    label: 'Att. %', w: 55, align: 'center', bold: true,
    get: (r) => `${r.percentage.toFixed(1)}%`,
    color: (r) => pctColor(r.percentage),
  },
];

const HISTORY_COLUMNS = [
  { label: 'Date', w: 90, get: (r) => r.date },
  { label: 'Class', w: 80, get: (r) => r.className },
  { label: 'Course/Program', w: 190, get: (r) => r.course },
  { label: 'Session', w: 80, get: (r) => r.session },
  {
    label: 'Status', w: 75, align: 'center', bold: true,
    get: (r) => r.status,
    color: (r) => (PDF_STATUS[r.status] ? PDF_STATUS[r.status].fg : PDF.text),
  },
];

// Daily, weekly, monthly and class reports (landscape)
const renderListPdf = (doc, result, meta) => {
  const { report } = result;
  const o = report.overall;
  const usable = doc.page.width - MARGIN * 2;

  drawBand(doc);

  doc.fillColor(PDF.text).font('Helvetica-Bold').fontSize(13);
  const title = fit(doc, report.title, usable);
  doc.text(title, MARGIN, 84, { width: usable, lineBreak: false });

  doc.fillColor(PDF.muted).font('Helvetica').fontSize(9);
  doc.text(`Period: ${report.period.label}`, MARGIN, 104, { width: usable, lineBreak: false });
  doc.text(`Filters: ${filterText(report.filters)}`, MARGIN, 117, { width: usable, lineBreak: false });
  doc.text(`Generated by ${meta.generatedBy} on ${stamp(meta.generatedAt)}`, MARGIN, 130, {
    width: usable,
    lineBreak: false,
  });

  const tilesBottom = drawTiles(doc, MARGIN, 150, usable, [
    { label: 'Students', value: o.students, bg: PDF.light, fg: PDF.primary },
    { label: 'Present Days', value: o.present, bg: PDF_STATUS.Present.bg, fg: PDF_STATUS.Present.fg },
    { label: 'Absent Days', value: o.absent, bg: PDF_STATUS.Absent.bg, fg: PDF_STATUS.Absent.fg },
    { label: 'Leave Days', value: o.leave, bg: PDF_STATUS.Leave.bg, fg: PDF_STATUS.Leave.fg },
    { label: 'Attendance', value: `${o.percentage.toFixed(1)}%`, bg: PDF.light, fg: PDF.primary },
  ]);

  const rows = report.students.map((s, i) => ({ ...s, n: i + 1 }));
  let y = drawTable(doc, MARGIN, tilesBottom + 14, LIST_COLUMNS, rows);

  if (y + ROW_H > doc.page.height - 55) {
    doc.addPage();
    y = MARGIN;
  }
  drawTotalsRow(doc, MARGIN, y, LIST_COLUMNS, 6, `Overall (${o.students} students)`, [
    o.present, o.absent, o.leave, o.totalDays, `${o.percentage.toFixed(1)}%`,
  ]);
};

// Student report (portrait)
const renderStudentPdf = (doc, result, meta) => {
  const { report } = result;
  const st = report.student;
  const o = report.overall;
  const usable = doc.page.width - MARGIN * 2;

  drawBand(doc);

  // Student details box
  const boxY = 86;
  const rowH = 38;
  const boxH = rowH * 4 + 8;
  doc.roundedRect(MARGIN, boxY, usable, boxH, 4).lineWidth(0.7).strokeColor(PDF.border).stroke();

  const details = [
    [['Student Name', st.fullName], ['Student ID', st.studentId]],
    [['Registration No.', st.registrationNumber], ['Year of Study', st.yearOfStudy]],
    [['Class', st.className], ['Course/Program', st.course]],
    [['Period', report.period.label], ['Generated by', meta.generatedBy]],
  ];
  details.forEach((pair, i) => {
    pair.forEach(([label, value], j) => {
      const cx = MARGIN + 12 + j * (usable / 2);
      const cy = boxY + 8 + i * rowH;
      const w = usable / 2 - 20;
      doc.fillColor(PDF.muted).font('Helvetica').fontSize(8);
      doc.text(label.toUpperCase(), cx, cy, { width: w, lineBreak: false });
      doc.fillColor(PDF.text).font('Helvetica-Bold').fontSize(11);
      const shown = fit(doc, value, w);
      doc.text(shown, cx, cy + 12, { width: w, lineBreak: false });
    });
  });

  // Summary tiles
  const tilesBottom = drawTiles(doc, MARGIN, boxY + boxH + 14, usable, [
    { label: 'Present', value: o.present, bg: PDF_STATUS.Present.bg, fg: PDF_STATUS.Present.fg },
    { label: 'Absent', value: o.absent, bg: PDF_STATUS.Absent.bg, fg: PDF_STATUS.Absent.fg },
    { label: 'Leave', value: o.leave, bg: PDF_STATUS.Leave.bg, fg: PDF_STATUS.Leave.fg },
    { label: 'Attendance', value: `${o.percentage.toFixed(1)}%`, bg: PDF.light, fg: PDF.primary },
  ]);

  // Day-by-day history
  doc.fillColor(PDF.primary).font('Helvetica-Bold').fontSize(12);
  doc.text(`Attendance History (${o.totalDays} days)`, MARGIN, tilesBottom + 18, {
    width: usable,
    lineBreak: false,
  });
  drawTable(doc, MARGIN, tilesBottom + 38, HISTORY_COLUMNS, report.records);
};

const addFooters = (doc, meta) => {
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i += 1) {
    doc.switchToPage(range.start + i);
    const usable = doc.page.width - MARGIN * 2;
    const y = doc.page.height - 30;
    const savedBottom = doc.page.margins.bottom;
    doc.page.margins.bottom = 0; // allow writing in the bottom margin without adding a page

    doc.fillColor(PDF.muted).font('Helvetica').fontSize(8);
    const left = fit(doc, `${SYSTEM_NAME}  |  Generated by ${meta.generatedBy} on ${stamp(meta.generatedAt)}`, usable - 90);
    doc.text(left, MARGIN, y, { width: usable, align: 'left', lineBreak: false });
    doc.text(`Page ${i + 1} of ${range.count}`, MARGIN, y, { width: usable, align: 'right', lineBreak: false });

    doc.page.margins.bottom = savedBottom;
  }
};

const buildPdf = (result, meta) =>
  new Promise((resolve, reject) => {
    try {
      const isStudent = result.reportType === 'student';
      const doc = new PDFDocument({
        size: 'A4',
        layout: isStudent ? 'portrait' : 'landscape',
        margin: MARGIN,
        bufferPages: true,
        info: { Title: result.reportName, Author: SYSTEM_NAME },
      });

      const chunks = [];
      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      if (isStudent) renderStudentPdf(doc, result, meta);
      else renderListPdf(doc, result, meta);

      addFooters(doc, meta);
      doc.end();
    } catch (err) {
      reject(err);
    }
  });

module.exports = { buildExcel, buildPdf };